import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { compileNewsletter, managedGrid, metadata } from '../server/newsletter.js';
import { patchDraft, draftOpportunityIds } from '../server/domain.js';
const source = JSON.parse(readFileSync(new URL('../templates/ijnet-newsletter.source.json', import.meta.url)));
const issue = JSON.parse(readFileSync(new URL('../output/newsletter-template/issue.example.json', import.meta.url)));
const make = () => compileNewsletter(source, structuredClone(issue));
test('full source structure, metadata, links and column proportions survive compilation', () => {
  const { lexical, manifest } = make();
  assert.equal(lexical.root.children.length, source.root.children.length);
  assert.deepEqual(manifest.sourceMetadata, source._meta);
  const find = id => lexical.root.children.find(n => metadata(n.html).id === id).html;
  assert.equal((find('insights-row').match(/<td /g) || []).length, 3);
  assert.equal((find('opportunities-grid').match(/<td /g) || []).length, 4);
  assert.match(find('breakdowns-row'), /width="66.67%"/);
  for (const label of ['The What:', 'The How:', 'The Why:']) assert.ok(find('spotlight').includes(label));
  assert.match(find('survey-cta-row'), /take our survey/);
  assert.match(find('footer-links'), /Unsubscribe/);
  assert.match(find('supporter-logo'), /<img/);
  assert.ok(!JSON.stringify(lexical).includes('{{'));
});
test('managed add and swap use record IDs and preserve every unrelated section', () => {
  const { lexical } = make();
  const before = structuredClone(lexical.root.children);
  const post = { id: 'draft', status: 'draft', lexical: JSON.stringify(lexical) };
  const a = { id: 'recA', title: 'Example opportunity 1', summary: '<script>unsafe</script>', url: 'https://example.com/a' };
  post.lexical = patchDraft(post, a);
  assert.ok(draftOpportunityIds(post).includes(a.id));
  assert.equal(patchDraft(post, { ...a, title: 'Renamed title' }), null);
  const b = { ...a, id: 'recB', title: 'Replacement' };
  post.lexical = patchDraft(post, b, { ...a, title: 'Renamed title' });
  assert.equal(patchDraft(post, b, a), null);
  assert.ok(draftOpportunityIds(post).includes(b.id));
  const after = JSON.parse(post.lexical);
  after.root.children.forEach((n, i) => { if (metadata(n.html).id !== 'opportunities-grid') assert.deepEqual(n, before[i]); });
  assert.match(managedGrid(after).node.html, /&lt;script&gt;/);
});
test('renamed heading does not affect targeting; missing/duplicate grids and manual edits fail safely', () => {
  const record = { id: 'recA', title: 'New opportunity' };
  const { lexical } = make();
  const heading = lexical.root.children.find(n => metadata(n.html).id === 'section-header-opportunities');
  heading.html = heading.html.replace('OPPORTUNITIES', 'Open calls');
  const post = { status: 'draft', lexical: JSON.stringify(lexical) };
  assert.ok(patchDraft(post, record));
  const grid = managedGrid(lexical);
  grid.node.html += '<p>Editor edit</p>';
  assert.throws(() => patchDraft({ ...post, lexical: JSON.stringify(lexical) }, record), /edited manually/);
  lexical.root.children.push(grid.node);
  assert.throws(() => patchDraft({ ...post, lexical: JSON.stringify(lexical) }, record), /Duplicate/);
  lexical.root.children = lexical.root.children.filter(n => n !== grid.node);
  assert.throws(() => patchDraft({ ...post, lexical: JSON.stringify(lexical) }, record), /missing/);
});
test('compiler escapes issue data, rejects unsafe URLs and supports optional survey', () => {
  const input = structuredClone(issue);
  input.includeSurvey = false;
  input.values.EDITORS_NOTE_BODY = '<img onerror="alert(1)">';
  const { lexical } = compileNewsletter(source, input);
  assert.equal(lexical.root.children.length, 25);
  assert.ok(lexical.root.children.some(n => n.html.includes('&lt;img')));
  input.values.HEADER_LOGO_URL = 'javascript:alert(1)';
  assert.throws(() => compileNewsletter(source, input), /HTTP/);
  delete input.values.HEADER_LOGO_URL;
  assert.throws(() => compileNewsletter(source, input), /Missing newsletter value/);
});
